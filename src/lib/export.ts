import type { DayStats } from "./days";
import { sha256Text } from "./sha256";
import {
  INVOICES,
  OFFERS,
  SUPPLIER_NIPS,
  productById,
  supplierById,
  type Invoice,
} from "@/data/mock";

const VAT_RATES = [0.05, 0.08, 0.23] as const;

export type LineRow = {
  lp: number;
  productId: string;
  productName: string; // по-польски, для юридических документов
  unit: string;
  qty: number;
  unitPrice: number;
  net: number;
  vatRate: number;
  vat: number;
  gross: number;
  savings: number; // сколько можно было сэкономить на этой позиции
};

export type InvoiceRow = Omit<Invoice, "lines"> & {
  supplierName: string;
  supplierNip: string;
  lines: LineRow[];
  net: number;
  vat: number;
  gross: number;
  savings: number;
  // суммы в разрезе ставок VAT: ключ это ставка в процентах ("5", "8", "23")
  netByRate: Record<string, number>;
  vatByRate: Record<string, number>;
};

const round2 = (n: number) => Math.round(n * 100) / 100;
const sum = (nums: number[]) => round2(nums.reduce((a, b) => a + b, 0));
const pct = (rate: number) => String(Math.round(rate * 100));

// month: "2026-10"
export function invoicesForMonth(month: string): InvoiceRow[] {
  return INVOICES.filter((inv) => inv.issueDate.startsWith(month)).map(
    (inv) => {
      const lines: LineRow[] = inv.lines.map((l, i) => {
        const net = round2(l.qty * l.unitPrice);
        const vat = round2(net * l.vatRate);
        const product = productById(l.productId);
        const best = Math.min(...Object.values(OFFERS[l.productId] ?? { x: l.unitPrice }));
        return {
          lp: i + 1,
          productId: l.productId,
          productName: product.namePl,
          unit: product.unit,
          qty: l.qty,
          unitPrice: l.unitPrice,
          net,
          vatRate: l.vatRate,
          vat,
          gross: round2(net + vat),
          savings: round2(Math.max(0, l.unitPrice - best) * l.qty),
        };
      });

      const netByRate: Record<string, number> = {};
      const vatByRate: Record<string, number> = {};
      for (const rate of VAT_RATES) {
        const group = lines.filter((l) => l.vatRate === rate);
        netByRate[pct(rate)] = sum(group.map((l) => l.net));
        vatByRate[pct(rate)] = sum(group.map((l) => l.vat));
      }

      return {
        ...inv,
        lines,
        supplierName: supplierById(inv.supplierId).name,
        supplierNip: SUPPLIER_NIPS[inv.supplierId] ?? "",
        net: sum(lines.map((l) => l.net)),
        vat: sum(lines.map((l) => l.vat)),
        gross: sum(lines.map((l) => l.gross)),
        savings: sum(lines.map((l) => l.savings)),
        netByRate,
        vatByRate,
      };
    },
  );
}

const xmlEscape = (s: string) =>
  s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

const money = (n: number) => n.toFixed(2);
const qtyStr = (n: number) => String(n);

// ───────── 1. JPK_V7M: ЧЕРНОВИК реестра закупок (по одной строке на счёт) ─────────
// Упрощённая структура, не проверена по схеме Минфина.
export function buildJpkXml(
  nip: string,
  month: string,
  rows: InvoiceRow[],
): string {
  const [year, mon] = month.split("-");
  const totalVat = sum(rows.map((r) => r.vat));

  const purchaseRows = rows
    .map(
      (r, i) => `    <ZakupWiersz>
      <LpZakupu>${i + 1}</LpZakupu>
      <KodKrajuNadaniaTIN>PL</KodKrajuNadaniaTIN>
      <NrDostawcy>${xmlEscape(r.supplierNip)}</NrDostawcy>
      <NazwaDostawcy>${xmlEscape(r.supplierName)}</NazwaDostawcy>
      <DowodZakupu>${xmlEscape(r.number)}</DowodZakupu>
      <DataZakupu>${r.issueDate}</DataZakupu>
      <DataWplywu>${r.saleDate}</DataWplywu>
      <K_42>${money(r.net)}</K_42>
      <K_43>${money(r.vat)}</K_43>
    </ZakupWiersz>`,
    )
    .join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- DRAFT generated by Costo from sample data. Not valid for filing. -->
<JPK>
  <Naglowek>
    <KodFormularza kodSystemowy="JPK_V7M (2)" wersjaSchemy="1-0E">JPK_VAT</KodFormularza>
    <WariantFormularza>2</WariantFormularza>
    <DataWytworzeniaJPK>${new Date().toISOString()}</DataWytworzeniaJPK>
    <NazwaSystemu>Costo</NazwaSystemu>
    <CelZlozenia poz="P_7">1</CelZlozenia>
    <Rok>${year}</Rok>
    <Miesiac>${Number(mon)}</Miesiac>
  </Naglowek>
  <Podmiot1 rola="Podatnik">
    <NIP>${xmlEscape(nip)}</NIP>
  </Podmiot1>
  <Ewidencja>
${purchaseRows}
    <ZakupCtrl>
      <LiczbaWierszyZakupow>${rows.length}</LiczbaWierszyZakupow>
      <PodatekNaliczony>${money(totalVat)}</PodatekNaliczony>
    </ZakupCtrl>
  </Ewidencja>
</JPK>
`;
}

// ───────── 2. XML со счетами и позициями (для разбора и сверки счетов) ─────────
// Структура в духе e-faktury, но не схема FA(3) и не для подачи в KSeF.
export function buildInvoicesXml(
  nip: string,
  month: string,
  rows: InvoiceRow[],
): string {
  const invoices = rows
    .map((r) => {
      const positions = r.lines
        .map(
          (l) => `        <Pozycja lp="${l.lp}">
          <Nazwa>${xmlEscape(l.productName)}</Nazwa>
          <Jednostka>${xmlEscape(l.unit)}</Jednostka>
          <Ilosc>${qtyStr(l.qty)}</Ilosc>
          <CenaNetto>${money(l.unitPrice)}</CenaNetto>
          <WartoscNetto>${money(l.net)}</WartoscNetto>
          <StawkaVAT>${pct(l.vatRate)}</StawkaVAT>
          <KwotaVAT>${money(l.vat)}</KwotaVAT>
          <WartoscBrutto>${money(l.gross)}</WartoscBrutto>
        </Pozycja>`,
        )
        .join("\n");

      const byRate = VAT_RATES.filter((rate) => r.netByRate[pct(rate)] > 0)
        .map(
          (rate) => `        <Stawka procent="${pct(rate)}">
          <Netto>${money(r.netByRate[pct(rate)])}</Netto>
          <VAT>${money(r.vatByRate[pct(rate)])}</VAT>
        </Stawka>`,
        )
        .join("\n");

      return `    <Faktura>
      <Naglowek>
        <Numer>${xmlEscape(r.number)}</Numer>
        <DataWystawienia>${r.issueDate}</DataWystawienia>
        <DataSprzedazy>${r.saleDate}</DataSprzedazy>
        <TerminPlatnosci>${r.dueDate}</TerminPlatnosci>
        <FormaPlatnosci>${r.paymentMethod}</FormaPlatnosci>
        <Waluta>EUR</Waluta>
      </Naglowek>
      <Sprzedawca>
        <NIP>${xmlEscape(r.supplierNip)}</NIP>
        <Nazwa>${xmlEscape(r.supplierName)}</Nazwa>
      </Sprzedawca>
      <Nabywca>
        <NIP>${xmlEscape(nip)}</NIP>
      </Nabywca>
      <Pozycje liczba="${r.lines.length}">
${positions}
      </Pozycje>
      <Podsumowanie>
${byRate}
        <Razem>
          <Netto>${money(r.net)}</Netto>
          <VAT>${money(r.vat)}</VAT>
          <Brutto>${money(r.gross)}</Brutto>
        </Razem>
      </Podsumowanie>
    </Faktura>`;
    })
    .join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- DRAFT generated by Costo from sample data. Not a KSeF FA(3) document. -->
<Faktury miesiac="${month}" nabywcaNIP="${xmlEscape(nip)}" liczba="${rows.length}">
${invoices}
</Faktury>
`;
}

// ───────── CSV: разделитель ";", запятая в числах, BOM для Excel ─────────
const num = (n: number) => money(n).replace(".", ",");
const text = (s: string) => `"${s.replace(/"/g, '""')}"`;

function toCsv(header: string[], lines: string[][]): string {
  return (
    "﻿" +
    [header, ...lines].map((cols) => cols.join(";")).join("\r\n") +
    "\r\n"
  );
}

// 3. Реестр закупок: одна строка на счёт, суммы разложены по ставкам VAT
export function buildRegisterCsv(rows: InvoiceRow[]): string {
  const header = [
    "Numer",
    "Data wystawienia",
    "Data sprzedazy",
    "Termin platnosci",
    "Forma platnosci",
    "Waluta",
    "NIP dostawcy",
    "Dostawca",
    ...VAT_RATES.flatMap((r) => [`Netto ${pct(r)}%`, `VAT ${pct(r)}%`]),
    "Netto razem",
    "VAT razem",
    "Brutto",
    "Liczba pozycji",
  ];
  const lines = rows.map((r) => [
    r.number,
    r.issueDate,
    r.saleDate,
    r.dueDate,
    r.paymentMethod,
    "EUR",
    r.supplierNip,
    text(r.supplierName),
    ...VAT_RATES.flatMap((rate) => [
      num(r.netByRate[pct(rate)]),
      num(r.vatByRate[pct(rate)]),
    ]),
    num(r.net),
    num(r.vat),
    num(r.gross),
    String(r.lines.length),
  ]);
  return toCsv(header, lines);
}

// 4. Позиции счетов: одна строка на товар, по номеру счёта сверяется с реестром
export function buildLinesCsv(rows: InvoiceRow[]): string {
  const header = [
    "Numer faktury",
    "Data wystawienia",
    "NIP dostawcy",
    "Lp",
    "Nazwa towaru",
    "Jednostka",
    "Ilosc",
    "Cena netto",
    "Wartosc netto",
    "Stawka VAT",
    "Kwota VAT",
    "Wartosc brutto",
  ];
  const lines = rows.flatMap((r) =>
    r.lines.map((l) => [
      r.number,
      r.issueDate,
      r.supplierNip,
      String(l.lp),
      text(l.productName),
      l.unit,
      String(l.qty).replace(".", ","),
      num(l.unitPrice),
      num(l.net),
      `${pct(l.vatRate)}%`,
      num(l.vat),
      num(l.gross),
    ]),
  );
  return toCsv(header, lines);
}

// ───────── Выбор документов и скачивание ─────────
export type DocKind = "jpk" | "invoicesXml" | "register" | "lines";
export const DOC_KINDS: DocKind[] = ["jpk", "invoicesXml", "register", "lines"];

export type GeneratedDoc = { filename: string; content: string; mime: string };

// label: период в имени файла, например "2026-10" или "2026-10-06_2026-10-12"
export function buildDocument(
  kind: DocKind,
  nip: string,
  month: string,
  rows: InvoiceRow[],
  label: string,
): GeneratedDoc {
  switch (kind) {
    case "jpk":
      return {
        filename: `JPK_V7M_${label}.xml`,
        content: buildJpkXml(nip, month, rows),
        mime: "application/xml",
      };
    case "invoicesXml":
      return {
        filename: `faktury_${label}.xml`,
        content: buildInvoicesXml(nip, month, rows),
        mime: "application/xml",
      };
    case "register":
      return {
        filename: `rejestr_zakupow_${label}.csv`,
        content: buildRegisterCsv(rows),
        mime: "text/csv;charset=utf-8",
      };
    case "lines":
      return {
        filename: `pozycje_faktur_${label}.csv`,
        content: buildLinesCsv(rows),
        mime: "text/csv;charset=utf-8",
      };
  }
}

export function downloadFile(
  filename: string,
  content: string | Blob,
  mime: string,
) {
  const blob = content instanceof Blob ? content : new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

// Паспорт выгрузки: что выгружено, за какой период, в каком состоянии были дни
// и контрольные суммы каждого файла. Нужен, чтобы позже доказать, что данные не менялись.
export function buildManifest(args: {
  nip: string;
  periodLabel: string;
  range: [string, string];
  days: DayStats[];
  docs: GeneratedDoc[];
  invoiceCount: number;
}): GeneratedDoc[] {
  const { nip, periodLabel, range, days, docs, invoiceCount } = args;
  const files = docs.map((d) => ({
    name: d.filename,
    sha256: sha256Text(d.content),
    bytes: new TextEncoder().encode(d.content).length,
  }));
  const hasOpenDays = days.some((d) => d.status === "open");

  const manifest = {
    generator: "Costo",
    generatedAt: new Date().toISOString(),
    taxpayerNip: nip,
    currency: "EUR",
    period: { label: periodLabel, from: range[0], to: range[1] },
    invoices: invoiceCount,
    days: days.map((d) => ({
      date: d.date,
      status: d.status,
      closedAt: d.closedAt,
      sha256: d.checksum,
    })),
    files,
    note: hasOpenDays
      ? "Period includes an open day: its data is preliminary and not yet fixed."
      : "All days in the period were closed automatically and are fixed.",
    disclaimer: "Draft generated from sample data. Not for filing.",
  };

  const sums = files.map((f) => `${f.sha256}  ${f.name}`).join("\n") + "\n";

  return [
    {
      filename: "manifest.json",
      content: JSON.stringify(manifest, null, 2) + "\n",
      mime: "application/json",
    },
    { filename: "SHA256SUMS.txt", content: sums, mime: "text/plain" },
  ];
}

// Один файл скачивается как есть, несколько упаковываются в ZIP
export async function downloadDocuments(
  docs: GeneratedDoc[],
  archiveName: string,
  extra: GeneratedDoc[] = [],
) {
  const all = [...docs, ...extra];
  if (all.length === 1) {
    downloadFile(all[0].filename, all[0].content, all[0].mime);
    return;
  }
  const { default: JSZip } = await import("jszip");
  const zip = new JSZip();
  for (const doc of all) zip.file(doc.filename, doc.content);
  const blob = await zip.generateAsync({ type: "blob" });
  downloadFile(`${archiveName}.zip`, blob, "application/zip");
}
